#!/bin/sh
# A stand-in for the app's chat while no model key is set (see README): the same turn agent-native's chat makes, with
# the screen injected as <current-screen> from the app's own view-screen action, and the app's actions as the only tools.
# Usage: tools/ask.sh "why did spend refuse ada?"     (run from spikes/generated-app, with the app and forman dev running)
cd "$(dirname "$0")/../app" || exit 1
export AGENT_USER_EMAIL=dev@local.test DO_NOT_TRACK=1 AGENT_NATIVE_TELEMETRY_DISABLED=1
screen=$(pnpm -s action view-screen)
claude -p "<current-screen>
$screen
</current-screen>

$1" \
  --append-system-prompt "You are the chat inside acme's app (generated by Forman). Answer from <current-screen> and the app's actions only, run as: pnpm -s action <name> '<json>'. Actions: read-page {path}, describe {name}, calls {operation?, outcome?, calledAs?}, trace {id}, page-tree {}. Read no files. Answer in a few plain sentences, naming the trace, the rule in the model and who the app called as." \
  --allowedTools "Bash(pnpm -s action:*)" --disallowedTools "Read,Grep,Glob,Edit,Write,WebFetch,WebSearch,Agent"
