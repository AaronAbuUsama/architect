import { connect, newActor, introduce, deployGovernance, register, gov, now } from "../lib/world.js";
import { Fr } from "@aztec/aztec.js/fields";
const w = await connect();
let t = now();
const [admin, m1] = [await newActor(w), await newActor(w)];
await introduce([admin, m1]);
console.log("actors", Math.round(now() - t)); t = now();
const g = await deployGovernance(w, admin);
console.log("deployed", Math.round(now() - t)); t = now();
await register(m1, g.instance);
await gov(admin, g.address).methods.open_proposal(1n, 777n).send({ from: admin.address, fee: w.fee });
console.log("opened", Math.round(now() - t)); t = now();
await gov(admin, g.address).methods.add_member(m1.address).send({ from: admin.address, fee: w.fee });
console.log("added", Math.round(now() - t)); t = now();
await m1.wallet.pxeEngine.sync();
console.log("is_member", (await gov(m1, g.address).methods.is_member(m1.address).simulate({ from: m1.address })).result);
await gov(m1, g.address).methods.vote(1n, true).send({ from: m1.address, fee: w.fee });
console.log("voted", Math.round(now() - t)); t = now();
console.log("get", JSON.stringify((await gov(m1, g.address).methods.get(1n).simulate({ from: m1.address })).result, (_, v) => typeof v === "bigint" ? v.toString() : v));
console.log("has_voted", (await gov(m1, g.address).methods.has_voted(1n, m1.address).simulate({ from: m1.address })).result);
process.exit(0);
