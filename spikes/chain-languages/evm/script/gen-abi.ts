// Writes gen/abi.ts: every ABI as an `as const` literal, so viem can type calls and events from it.
import { readFileSync, writeFileSync } from "node:fs";
const files: Record<string, string> = {
  governance: "Governance.sol/Governance", miniDao: "MiniDao.sol/MiniDao", gatedDao: "GatedDao.sol/GatedDao",
  testToken: "TestToken.sol/TestToken", pausedToken: "Hostile.sol/PausedToken", codedDao: "CodedDao.sol/CodedDao",
};
let out = "// Generated by script/gen-abi.ts from forge artifacts. Do not edit.\n";
for (const [k, f] of Object.entries(files)) {
  const abi = JSON.parse(readFileSync(`out/${f}.json`, "utf8")).abi;
  out += `export const ${k}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync("gen/abi.ts", out);
console.log("wrote gen/abi.ts");
