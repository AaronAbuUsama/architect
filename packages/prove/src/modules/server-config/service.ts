import { existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { Effect } from "effect";
import type { ServerConfigApi } from "./types.ts";
import { parseJsonc } from "./internal/jsonc.ts";

type Base = { readonly main?: string; readonly d1_databases?: ReadonlyArray<Record<string, unknown>> } & Record<string, unknown>;

/** The Worker's binding to the portal's static files; `@orthograph/portal/server` reads it as `PORTAL_ASSETS`. */
export const ASSETS_BINDING = "PORTAL_ASSETS";

const clientOf: ServerConfigApi["clientOf"] = (root) =>
  Effect.runSync(
    Effect.try({ try: () => dirname(createRequire(join(resolve(root), "package.json")).resolve("@orthograph/portal/package.json")), catch: () => undefined }).pipe(
      Effect.map((portal) => join(portal, "dist/client")),
      Effect.map((client) => (existsSync(join(client, "index.html")) ? client : undefined)),
      Effect.catch(() => Effect.succeed(undefined)),
    ),
  );

const derive: ServerConfigApi["derive"] = (root, baseText, assets) => {
  const base = parseJsonc(baseText) as Base;
  const folder = resolve(root, "generated/server");
  const config = {
    ...base,
    main: resolve(folder, base.main ?? "main.ts"),
    d1_databases: (base.d1_databases ?? []).map((db) => ({ ...db, migrations_dir: resolve(folder, String(db["migrations_dir"] ?? "migrations")) })),
    ...(assets === undefined ? {} : { assets: { directory: assets, binding: ASSETS_BINDING, run_worker_first: true } }),
  };
  return `// Generated by ortho from generated/server/wrangler.jsonc. Do not edit.\n${JSON.stringify(config, null, 2)}\n`;
};

export const ServerConfig: ServerConfigApi = { parse: parseJsonc, clientOf, derive };
